#!/usr/bin/env node
/* Generates a synthetic public/forecast.json so the app runs locally without
 * a scrape. Flagged `synthetic: true`, which the UI surfaces as a banner —
 * sample data must never be mistakable for a real forecast.
 *
 * The real file comes from `npm run scrape`, which the Action runs. */

import { writeFile, mkdir } from "node:fs/promises";
import { readFile } from "node:fs/promises";
import { parseResortPage } from "./parse.js";
import { buildPage } from "../test/sf-fixture.js";

const root = new URL("..", import.meta.url).pathname;
const cfg = JSON.parse(await readFile(`${root}src/data/resorts.json`, "utf8"));
const now = new Date();

const dayNames = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];
const headers = Array.from({ length: 6 }, (_, i) => {
  const d = new Date(now); d.setUTCDate(d.getUTCDate() + i);
  return `${dayNames[d.getUTCDay()]}${d.getUTCDate()}`;
});

// Deterministic pseudo-variation so the table has something to rank.
const seeded = (n) => { let x = Math.sin(n) * 10000; return x - Math.floor(x); };

const resorts = cfg.resorts.map((r, ri) => {
  const snow = Array.from({ length: 18 }, (_, i) => {
    const v = seeded(ri * 31 + i) * (ri % 3 === 0 ? 14 : 5);
    return v < 1.2 ? "—" : v.toFixed(1);
  });
  // Winter conditions, so the sample looks like the app in season. A summer
  // spread flags a warm dot on almost every resort and misrepresents the UI.
  const tmax = Array.from({ length: 18 }, (_, i) => Math.round(-13 + seeded(ri * 7 + i) * 14));
  const tmin = tmax.map((t) => t - 5);
  // Only some resorts should reach lift-hold winds. Taking the max of 18
  // samples from a wide range flags essentially everything.
  const gusty = ri % 4 === 0;
  const wind = Array.from({ length: 18 }, (_, i) =>
    `${Math.round(seeded(ri * 13 + i) * (gusty ? 70 : 38))}${["N", "NW", "S", "SE"][i % 4]}`);
  const freeze = Array.from({ length: 18 }, (_, i) => Math.round(600 + seeded(ri * 3 + i) * 2400));
  const base = 1800 + Math.round(seeded(ri) * 1200);

  const parsed = parseResortPage(
    buildPage({ headers, snow, tmax, tmin, wind, freeze, elev: [base + 700, base, base - 600] }),
    { now }
  );
  return { id: r.id, name: r.name, region: r.region, slugs: r.slugs, ...parsed };
});

// Three days of history so "-3 days" renders rather than sitting at "—".
// Marked synthetic so a later real scrape discards it rather than
// appending observed snowfall onto invented numbers.
const history = { synthetic: true, days: {}, updatedAt: now.toISOString() };
for (let i = 1; i <= 3; i++) {
  const d = new Date(now); d.setUTCDate(d.getUTCDate() - i);
  const key = d.toISOString().slice(0, 10);
  history.days[key] = Object.fromEntries(
    resorts.map((r, ri) => [r.id, Number((seeded(ri * 17 + i) * 9).toFixed(1))])
  );
}

await mkdir(`${root}public`, { recursive: true });
await writeFile(`${root}public/forecast.json`, JSON.stringify({
  generatedAt: now.toISOString(),
  synthetic: true,
  source: "synthetic — generated by scripts/make-dev-fixture.js",
  tier: cfg.tier, combineRule: cfg.combine?.rule,
  units: { snow: "cm", temp: "C", wind: "km/h", elevation: "m" },
  horizonDays: 6, resortCount: resorts.length, failures: [], resorts,
}, null, 1));
await writeFile(`${root}public/history.json`, JSON.stringify(history, null, 1));
console.error(`wrote synthetic public/forecast.json (${resorts.length} resorts) + history.json`);
